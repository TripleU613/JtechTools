// Font Awesome's solid icons that mean "on" next to an outline "off" (liked
// vs not, bookmarked vs not): drawn filled so the state still shows.
export const JT_FILLED_ICONS: readonly string[] = [
  "bookmark",
  "circle",
  "heart",
  "square-full",
  "star",
];

// The sprite's symbol for a Font Awesome icon
export function jtIconId(faIcon: string): string | undefined {
  const lucide = JT_ICON_MAP[faIcon];
  if (!lucide) {
    return undefined;
  }
  return JT_FILLED_ICONS.includes(faIcon)
    ? `jt-${lucide}-fill`
    : `jt-${lucide}`;
}
